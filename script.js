const analyticsConfig = window.ANALYTICS_CONFIG || {};
const validGtmId = /^GTM-[A-Z0-9]{6,}$/i.test(analyticsConfig.gtmContainerId || "");
const validPrivacyUrl = (() => {
  try {
    return ["http:", "https:"].includes(new URL(analyticsConfig.privacyPolicyUrl).protocol);
  } catch (_error) {
    return false;
  }
})();
const analyticsAvailable = validGtmId && validPrivacyUrl;
const consentKey = analyticsConfig.consentStorageKey || "am_analytics_consent_v1";
let currentLanguage = SITE.defaultLanguage;
let analyticsLoaded = false;

function safeStorageGet(key) {
  try { return window.localStorage.getItem(key); } catch (_error) { return null; }
}

function safeStorageSet(key, value) {
  try { window.localStorage.setItem(key, value); } catch (_error) { /* Storage is optional. */ }
}

function consentState() {
  return safeStorageGet(consentKey);
}

function consentPayload(analyticsValue) {
  return {
    ad_storage: "denied",
    ad_user_data: "denied",
    ad_personalization: "denied",
    analytics_storage: analyticsValue
  };
}

function pushConsent(command, value) {
  window.dataLayer = window.dataLayer || [];
  window.gtag = window.gtag || function gtag() { window.dataLayer.push(arguments); };
  window.gtag("consent", command, consentPayload(value));
}

function loadGtm() {
  if (!analyticsAvailable || consentState() !== "granted") return;
  if (analyticsLoaded) {
    pushConsent("update", "granted");
    return;
  }
  analyticsLoaded = true;
  pushConsent("default", "denied");
  pushConsent("update", "granted");
  window.dataLayer.push({ "gtm.start": Date.now(), event: "gtm.js" });
  const script = document.createElement("script");
  script.async = true;
  script.id = "google-tag-manager";
  script.src = `https://www.googletagmanager.com/gtm.js?id=${encodeURIComponent(analyticsConfig.gtmContainerId)}`;
  document.head.appendChild(script);
}

function trackEvent(event, parameters = {}) {
  if (!analyticsAvailable || consentState() !== "granted" || !analyticsLoaded) return false;
  window.dataLayer = window.dataLayer || [];
  window.dataLayer.push({ event, ...parameters, language: currentLanguage });
  return true;
}

function whatsappUrl(language) {
  return `https://wa.me/${SITE.whatsappNumber}?text=${encodeURIComponent(copy[language].whatsappMessage)}`;
}

function setMeta(selector, value) {
  const element = document.querySelector(selector);
  if (element) element.setAttribute("content", value);
}

function applyLanguage(language, shouldTrack = false) {
  if (!copy[language]) return;
  const previousLanguage = currentLanguage;
  currentLanguage = language;
  const dictionary = copy[language];
  document.documentElement.lang = language;
  document.title = dictionary.documentTitle;
  setMeta('meta[name="description"]', dictionary.metaDescription);
  setMeta('meta[property="og:locale"]', language === "tr" ? "tr_TR" : "en_US");
  setMeta('meta[property="og:title"]', dictionary.documentTitle);
  setMeta('meta[property="og:description"]', dictionary.ogDescription);
  setMeta('meta[name="twitter:title"]', dictionary.documentTitle);
  setMeta('meta[name="twitter:description"]', dictionary.ogDescription);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (typeof value === "string") element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAriaLabel];
    if (typeof value === "string") element.setAttribute("aria-label", value);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAlt];
    if (typeof value === "string") element.setAttribute("alt", value);
  });
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === language));
  });
  document.querySelectorAll('[data-contact="whatsapp"]').forEach((link) => { link.href = whatsappUrl(language); });
  document.querySelectorAll('[data-contact="phone"]').forEach((link) => { link.href = SITE.phoneUrl; });
  document.querySelectorAll('[data-contact="email"]').forEach((link) => { link.href = SITE.emailUrl; });
  safeStorageSet("am_preferred_language", language);

  if (shouldTrack && previousLanguage !== language) {
    trackEvent("language_change", { from_language: previousLanguage });
  }
}

function closeMenu() {
  const menu = document.querySelector("[data-menu]");
  const toggle = document.querySelector("[data-menu-toggle]");
  if (!menu || !toggle) return;
  menu.classList.remove("is-open");
  toggle.setAttribute("aria-expanded", "false");
  toggle.setAttribute("aria-label", copy[currentLanguage].menuOpen);
  document.body.classList.remove("menu-open");
}

function initNavigation() {
  const menu = document.querySelector("[data-menu]");
  const toggle = document.querySelector("[data-menu-toggle]");
  if (!menu || !toggle) return;
  toggle.addEventListener("click", () => {
    const open = toggle.getAttribute("aria-expanded") !== "true";
    menu.classList.toggle("is-open", open);
    toggle.setAttribute("aria-expanded", String(open));
    toggle.setAttribute("aria-label", copy[currentLanguage][open ? "menuClose" : "menuOpen"]);
    document.body.classList.toggle("menu-open", open);
  });
  menu.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeMenu));
  window.addEventListener("resize", () => { if (window.innerWidth > 980) closeMenu(); });
  window.addEventListener("scroll", () => document.querySelector("[data-header]")?.classList.toggle("is-scrolled", window.scrollY > 8), { passive: true });
}

function showConsent() {
  const panel = document.querySelector("[data-consent]");
  if (!analyticsAvailable || !panel) return;
  panel.hidden = false;
  document.documentElement.classList.add("has-open-consent");
  panel.querySelector("button")?.focus();
}

function hideConsent() {
  const panel = document.querySelector("[data-consent]");
  if (panel) panel.hidden = true;
  document.documentElement.classList.remove("has-open-consent");
}

function initConsent() {
  const settings = document.querySelector("[data-consent-settings]");
  const privacyLink = document.querySelector("[data-privacy-link]");
  if (!analyticsAvailable) return;
  if (settings) settings.hidden = false;
  if (privacyLink) privacyLink.href = analyticsConfig.privacyPolicyUrl;
  settings?.addEventListener("click", showConsent);
  document.querySelector("[data-consent-accept]")?.addEventListener("click", () => {
    safeStorageSet(consentKey, "granted");
    hideConsent();
    loadGtm();
  });
  document.querySelector("[data-consent-reject]")?.addEventListener("click", () => {
    safeStorageSet(consentKey, "denied");
    if (analyticsLoaded) pushConsent("update", "denied");
    hideConsent();
  });
  if (consentState() === "granted") loadGtm();
  else if (consentState() !== "denied") showConsent();
}

function initProjectImageFallbacks() {
  document.querySelectorAll("[data-project-image]").forEach((image) => {
    const showFallback = () => image.classList.add("is-broken");
    image.addEventListener("error", showFallback, { once: true });
    if (image.complete && image.naturalWidth === 0) showFallback();
  });
}

function initVideos() {
  const videos = [...document.querySelectorAll("[data-video]")];
  if (!videos.length) return;
  const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

  videos.forEach((video) => {
    const stage = video.closest("[data-video-stage]");
    const button = stage?.querySelector("[data-video-play]");
    const poster = stage?.querySelector("[data-video-poster]");
    const errorMessage = stage?.querySelector("[data-video-error]");
    if (!stage || !button || !poster || !errorMessage) return;

    const fail = () => {
      video.pause();
      video.removeAttribute("src");
      video.hidden = true;
      poster.hidden = false;
      button.hidden = true;
      errorMessage.hidden = false;
      stage.classList.add("has-error");
    };

    button.addEventListener("click", () => {
      if (video.src) return;
      button.disabled = true;
      const label = button.querySelector("span:last-child");
      if (label) label.textContent = copy[currentLanguage].mediaLoading;
      video.src = video.dataset.src;
      video.load();
    });

    video.addEventListener("loadeddata", () => {
      stage.classList.add("is-ready");
      poster.hidden = true;
      errorMessage.hidden = true;
      button.hidden = true;
      video.hidden = false;
      button.disabled = false;
      if (reduceMotion) video.focus();
      else video.play().catch(() => { /* Native controls remain available. */ });
    }, { once: true });

    video.addEventListener("error", fail, { once: true });
    video.addEventListener("play", () => {
      videos.forEach((otherVideo) => { if (otherVideo !== video) otherVideo.pause(); });
      if (!video.dataset.analyticsPlayed) {
        video.dataset.analyticsPlayed = "true";
        trackEvent("video_engagement", { video_id: video.dataset.videoId, action: "play" });
      }
    });
  });

  const section = document.querySelector(".media-showcase");
  if (section && "IntersectionObserver" in window) {
    const observer = new IntersectionObserver(([entry]) => {
      if (!entry.isIntersecting) videos.forEach((video) => video.pause());
    }, { threshold: 0.15 });
    observer.observe(section);
  }
  document.addEventListener("visibilitychange", () => {
    if (document.hidden) videos.forEach((video) => video.pause());
  });
}

function initInteractionTracking() {
  document.addEventListener("click", (event) => {
    const languageButton = event.target.closest("[data-lang]");
    if (languageButton) {
      applyLanguage(languageButton.dataset.lang, true);
      return;
    }
    const projectLink = event.target.closest("[data-project]");
    if (projectLink) trackEvent("portfolio_click", { project_id: projectLink.dataset.project });
    const serviceLink = event.target.closest("[data-service]");
    if (serviceLink) trackEvent("service_interest", { service_id: serviceLink.dataset.service });
    const contactLink = event.target.closest("[data-contact]");
    if (contactLink) {
      trackEvent("contact_click", {
        contact_method: contactLink.dataset.contact,
        cta_location: contactLink.dataset.location || "unknown"
      });
    }
  });
}

function init() {
  const storedLanguage = safeStorageGet("am_preferred_language");
  applyLanguage(copy[storedLanguage] ? storedLanguage : SITE.defaultLanguage);
  document.querySelectorAll("[data-year]").forEach((element) => { element.textContent = new Date().getFullYear(); });
  initNavigation();
  initProjectImageFallbacks();
  initVideos();
  initInteractionTracking();
  initConsent();
}

document.addEventListener("DOMContentLoaded", init, { once: true });
